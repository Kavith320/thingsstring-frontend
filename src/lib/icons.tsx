/** Render an icon reference. Falls back to `fallback` (or nothing) for null/unknown refs. */
export function IconRef({
    value,
    fallback: Fallback,
    className,
    alt = "",
}: {
    value?: string | null;
    fallback?: IconComponent;
    className?: string;
    alt?: string;
}) {
    const v = value || "";
    const [set, ...rest] = v.split(":");
    const name = rest.join(":");

    if (set === "file" && /^[a-f0-9]{32}$/.test(name)) {
        // eslint-disable-next-line @next/next/no-img-element -- user upload served by the backend
        return <img src={fileUrl(name)} alt={alt} className={cn("object-cover", className)} loading="lazy" />;
    }
    if (set === "emoji" && name) {
        return <span className={cn("inline-flex items-center justify-center leading-none", className)} role="img" aria-label={alt || undefined}>{name}</span>;
    }
    if (set === "avatar" && AVATARS[name]) {
        const A = AVATARS[name].icon;
        return <A className={className} aria-hidden />;
    }
    const Icon = ICON_BY_REF[v] || Fallback;
    return Icon ? <Icon className={className} aria-hidden /> : null;
}

/** Profile avatar: uploaded photo, built-in avatar, emoji, or initials. */
export function Avatar({ value, name, size = 40, className }: { value?: string | null; name?: string | null; size?: number; className?: string }) {
    const v = value || "";
    const [set, ...rest] = v.split(":");
    const key = rest.join(":");
    const style = { width: size, height: size };
    const base = cn("inline-flex shrink-0 items-center justify-center overflow-hidden rounded-full", className);

    if (set === "file" && /^[a-f0-9]{32}$/.test(key)) {
        // eslint-disable-next-line @next/next/no-img-element -- user upload served by the backend
        return <img src={fileUrl(key)} alt="" style={style} className={cn(base, "object-cover")} />;
    }
    if (set === "avatar" && AVATARS[key]) {
        const { icon: Icon, bg } = AVATARS[key];
        return (
            <span style={style} className={cn(base, "bg-gradient-to-br text-white", bg)}>
                <Icon style={{ width: size * 0.5, height: size * 0.5 }} aria-hidden />
            </span>
        );
    }
    if (set === "emoji" && key) {
        return <span style={{ ...style, fontSize: size * 0.55 }} className={cn(base, "bg-zinc-100 dark:bg-zinc-800")}>{key}</span>;
    }
    const initials = (name || "?").trim().split(/\s+/).slice(0, 2).map((w) => w[0]?.toUpperCase()).join("") || "?";
    return (
        <span style={{ ...style, fontSize: size * 0.38 }} className={cn(base, "bg-zinc-200 font-semibold text-zinc-700 dark:bg-zinc-800 dark:text-zinc-200")}>
            {initials}
        </span>
    );
}
